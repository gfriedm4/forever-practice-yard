// Writes src/specs/manifest.gen.ts: what every spec and build is called, and
// how to load one. The picker, the planner and the yard's spec list only need
// the names, so with this they no longer pull in all nine classes' abilities;
// the yard loads the single spec being played through SPEC_LOADERS.
// Run: npm run specs
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const INDEX = 'src/specs/index.ts';
const OUT = 'src/specs/manifest.gen.ts';
const BUNDLE = 'node_modules/.cache/spec_manifest.mjs';

// Which module each spec is exported from, read off the index's own imports.
const source = readFileSync(INDEX, 'utf8');
const modules = [];
for (const m of source.matchAll(/^import \{([^}]+)\} from '(\.[^']+)';$/gm)) {
  const names = m[1].split(',').map((n) => n.trim()).filter(Boolean);
  if (names.length) modules.push({ path: m[2], names });
}
if (!modules.length) throw new Error(`no spec imports found in ${INDEX}`);

// Bundle the specs for node, so we can read the real objects rather than parse them.
const entry = [...modules.map((m) => `export { ${m.names.join(', ')} } from '${m.path}';`), `export { SPECS } from './index';`].join('\n');
await build({
  stdin: { contents: entry, resolveDir: 'src/specs', sourcefile: 'manifest_entry.ts', loader: 'ts' },
  bundle: true, platform: 'node', format: 'esm', outfile: BUNDLE, logLevel: 'warning',
});
const loaded = await import(`${pathToFileURL(BUNDLE).href}?v=${Date.now()}`);

// Spec object -> the module and export name it came from.
const origin = new Map();
for (const m of modules) for (const name of m.names) if (loaded[name]) origin.set(loaded[name], { path: m.path, name });

const q = (s) => JSON.stringify(s);
const metaOf = (s) => {
  const builds = (s.builds ?? []).map((b) => {
    const fields = [`id: ${q(b.id)}`, `label: ${q(b.label)}`];
    if (b.name) fields.push(`name: ${q(b.name)}`);
    if (b.source) fields.push(`source: ${q(b.source)}`);
    if (b.talentString) fields.push(`talentString: ${q(b.talentString)}`);
    return `      { ${fields.join(', ')} }`;
  });
  return `  {\n    id: ${q(s.id)}, className: ${q(s.className)}, specName: ${q(s.specName)},\n    look: ${JSON.stringify(s.look)},\n    builds: [\n${builds.join(',\n')}${builds.length ? ',\n' : ''}    ],\n  }`;
};

const loaderOf = (s) => {
  const o = origin.get(s);
  if (!o) throw new Error(`spec ${s.id} is not exported from any module imported by ${INDEX}`);
  return `  ${q(s.id)}: () => import(${q(o.path)}).then((m) => m.${o.name}),`;
};

const out = `// Generated by tools/spec_manifest.mjs (npm run specs) -- do not edit.
// The name of every spec and build, and a loader per spec. Reading this instead
// of ../specs keeps all nine classes' abilities off the first screen and out of
// the yard's own chunk: the yard loads just the spec being played.
import type { CharacterLook, Spec } from '../engine/types';

/** A build as the picker, the planner and the yard's spec list need it: its names and its talents. */
export interface BuildMeta {
  id: string;
  label: string;
  name?: string;
  source?: string;
  talentString?: string;
}

/** A spec as the lists need it, without its abilities, gear or priority list. */
export interface SpecMeta {
  id: string;
  className: string;
  specName: string;
  /** How the class dresses, so another spec's look can be worn without loading that spec. */
  look: CharacterLook;
  builds: BuildMeta[];
}

/** Every spec, in the order ../specs lists them. */
export const SPEC_META: SpecMeta[] = [
${loaded.SPECS.map(metaOf).join(',\n')},
];

/** How a class dresses: for the raid's own characters in Onyxia's Lair. */
export function specLook(id: string): CharacterLook {
  const meta = SPEC_META.find((s) => s.id === id);
  if (!meta) throw new Error(\`unknown spec: \${id}\`);
  return meta.look;
}

/** Loads one spec with everything it needs to be played. */
export const SPEC_LOADERS: Record<string, () => Promise<Spec>> = {
${loaded.SPECS.map(loaderOf).join('\n')}
};
`;
writeFileSync(OUT, out);
console.log(`${OUT}: ${loaded.SPECS.length} specs, ${loaded.SPECS.reduce((n, s) => n + (s.builds?.length ?? 0), 0)} builds`);
